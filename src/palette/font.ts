export const GLYPH_W = 5;
export const GLYPH_H = 7;

const bits = new Map<string, boolean[][]>(Object.entries(GLYPHS).map(([c, rows]) => [c, rows.map((r) => [...r].map((ch) => ch === "#"))]));

export function glyph(ch: string): boolean[][] | undefined {
  return bits.get(ch.toUpperCase());
}

/** Width in pixels of `text` at `scale`, with 1px (scaled) spacing between glyphs. */
export function textWidth(text: string, scale = 1): number {
  return text.length === 0 ? 0 : (text.length * (GLYPH_W + 1) - 1) * scale;
}
