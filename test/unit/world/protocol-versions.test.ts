function roundTrips(dir: string): void {
  for (const name of names(dir)) {
    if (name === "patch-large") continue; // generated by a rule; unchanged since protocol 1 and checked byte for byte in protocol.test.ts
    it(`${name}: the current codec decodes it to its sidecar and re-encodes it byte for byte`, () => {
      const bin = new Uint8Array(readFileSync(join(dir, `${name}.bin`)));
      const side = sidecar(dir, name);
      const decoded = decodeFrame(bin, side.sender);
      expect(sidecarOf(side.description, side.sender, decoded, bin)).toEqual({ ...side, ...(side.body ? {} : { body: undefined }) });
      expect(hex(encodeMessage(messageOf(side)))).toBe(hex(bin));
      expect(hex(encodeMessage(decoded))).toBe(hex(bin));
    });
  }
}

