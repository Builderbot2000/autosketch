describe("protocol 3 additions in the codec", () => {
  const raw = (header: Record<string, unknown>, body = new Uint8Array(0)) => {
    const h = Buffer.from(JSON.stringify(header));
    const out = new Uint8Array(8 + h.length + body.length);
    const v = new DataView(out.buffer);
    v.setUint32(0, 4 + h.length + body.length);
    v.setUint32(4, h.length);
    out.set(h, 8);
    out.set(body, 8 + h.length);
    return out;
  };

  it("validates registry requests and results", () => {
    expect(() => decodeFrame(raw({ type: "registry", id: 1, have: "XYZ" }), "mcp")).toThrow(/have must be 16 lowercase hex digits/);
    const ok = { type: "registry.result", id: 1, hash: "0123456789abcdef", dataVersion: 3955 };
    expect(() => decodeFrame(raw(ok), "mod")).toThrow(/needs the report as its body/);
    expect(() => decodeFrame(raw({ ...ok, unchanged: true }, Uint8Array.of(1)), "mod")).toThrow(/carries no body/);
    expect(decodeFrame(raw({ ...ok, unchanged: true }), "mod")).toEqual({ ...ok, unchanged: true });
    expect(decodeFrame(raw(ok, Uint8Array.of(1, 2)), "mod")).toMatchObject({ report: Uint8Array.of(1, 2) });
  });

  it("round-trips upgrades of both kinds, and refuses a structure body with two compounds", () => {
    const c = { type: "compound", value: { id: { type: "string", value: "minecraft:chest" } } } as const;
    const m = { type: "upgrade", id: 4, from: 3465, kind: "elements", states: ["minecraft:grass", "minecraft:grass"], blockEntities: [c], entities: [] } as const;
    expect(decodeFrame(encodeMessage(m), "mcp")).toEqual(m);
    const r = { type: "upgrade.result", id: 4, to: 3955, failed: 2, kind: "structure", structure: c } as const;
    expect(decodeFrame(encodeMessage(r), "mod")).toEqual(r);
    const bad = encodeMessage({ ...m, kind: "elements", states: [], blockEntities: [c, c] });
    const header = splitFrame(bad.subarray(4)).header;
    const body = splitFrame(bad.subarray(4)).body.subarray(1); // drop the empty state list: two compounds remain
    expect(() => decodeFrame(raw({ ...header, kind: "structure" }, body), "mcp")).toThrow(/2 compounds, expected 1/);
  });
});

describe("protocol 2 additions in the codec", () => {
  const frame = (header: Record<string, unknown>, body = new Uint8Array(0)) => {
    const h = Buffer.from(JSON.stringify(header));
    const out = new Uint8Array(4 + h.length + body.length);
    new DataView(out.buffer).setUint32(0, h.length);
    out.set(h, 4);
    out.set(body, 4 + h.length);
    return out;
  };
  const decode = (header: Record<string, unknown>, sender: "mcp" | "mod") => {
    const f = frame(header);
    const full = new Uint8Array(4 + f.length);
    new DataView(full.buffer).setUint32(0, f.length);
    full.set(f, 4);
    return decodeFrame(full, sender);
  };
  const ctx = { dimension: OW, position: [0, 0, 0], eye: [0, 1.62, 0], yaw: 0, pitch: 0, facing: "south" };
  const prompt = { type: "prompt", id: 1, player: HOST, text: "hi", context: ctx };

  it("validates modes, the scan grant and surface snapshots", () => {
    expect(decode({ ...prompt, mode: "plan" }, "mod")).toMatchObject({ mode: "plan" });
    expect(() => decode({ ...prompt, mode: "destroy" }, "mod")).toThrow(ProtocolError);
    const scan = { radius: 4, columns: { min: [0, 0], max: [143, 143] }, box: { min: [0, 0, 0], max: [143, 96, 143] } };
    expect(() => decode({ ...prompt, mode: "ask", scan }, "mod")).toThrow(/only with mode scan/);
    expect(decode({ ...prompt, mode: "scan", scan }, "mod")).toMatchObject({ scan });
    expect(() => decode({ type: "hello", protocol: 2, token: "t", client: { name: "a", version: "1" }, volatile: {}, modes: ["build", "nope"] }, "mcp")).toThrow(/modes\[1\]/);
    expect(() => decode({ type: "snapshot", id: 1, dimension: OW, kind: "surface", boxes: [WORK] }, "mcp")).toThrow(/columns, not boxes/);
    expect(() => decode({ type: "snapshot", id: 1, dimension: OW, boxes: [WORK], ceiling: 3 }, "mcp")).toThrow(/belong to a surface/);
    expect(() => decode({ type: "snapshot", id: 1, dimension: OW, kind: "surface", columns: { min: [5, 0], max: [4, 0] } }, "mcp")).toThrow(/min must not exceed max/);
    expect(decode({ type: "snapshot", id: 1, dimension: OW, kind: "surface", columns: { min: [0, 0], max: [1, 1] }, ceiling: -10 }, "mcp")).toMatchObject({ ceiling: -10 });
  });

  it("encodes a surface result with ceilings only when ceiling is given", () => {
    const layer = { heights: Uint32Array.of(0, 5), states: Uint32Array.of(0, 0) };
    const base: SurfaceResult = { type: "snapshot.result", id: 2, dimension: OW, kind: "surface", columns: { min: [0, 0], max: [1, 0] }, minY: -64, missing: [], palette: ["minecraft:stone"], surface: layer };
    expect(() => encodeMessage({ ...base, ceiling: 0 })).toThrow(/exactly when ceiling/);
    expect(() => encodeMessage({ ...base, ceilings: layer })).toThrow(/exactly when ceiling/);
    const back = decodeFrame(encodeMessage({ ...base, ceiling: 0, ceilings: layer }), "mod") as SurfaceResult;
    expect(Array.from(back.ceilings!.heights)).toEqual([0, 5]);
  });

  it("reads features and modes from hellos, never from the version number", () => {
    const hello = { type: "hello", protocol: 2, mod: { version: "x" }, game: { version: "1.21.1", dataVersion: 3955, loader: "neoforge", loaderVersion: "1" }, singleplayer: true, host: null } as ModHello;
    expect(modHas(hello, "volumes.set")).toBe(false); // protocol 2 without the feature listed
    expect(modHas({ ...hello, protocol: 1, features: ["volumes.set"] }, "volumes.set")).toBe(true);
    expect(helloModes({})).toEqual(["build"]);
    expect(helloModes({ modes: ["ask"] })).toEqual(["ask"]);
  });
});

