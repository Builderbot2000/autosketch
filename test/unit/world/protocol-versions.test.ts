describe("an unlinked session", () => {
  it("gives the same results with no game, a protocol-2 game and a protocol-3 game connected but not linked", async () => {
    const ctx = fixtureContext();
    const run = async (protocol?: number) => {
      const workspace = tempDir();
      const session = new Session(workspace);
      let host: FakeHost | undefined, link: LiveLink | undefined;
      if (protocol !== undefined) {
        host = await FakeHost.start({ protocol }); // no work volume: connected, nothing linked
        link = new LiveLink(session, { backoff: { minMs: 20, maxMs: 50 } });
        link.setSync(syncLink);
        session.world = link;
        session.callHooks.push(autoSyncHook(() => session.world));
        link.autoLink({ instanceDir: host.instanceDir, plugins: [], palettes: new PaletteBook() });
        await host.waitFor(() => link!.bridge.connected);
      }
      const server = createServer(ctx, { session });
      const [a, b] = InMemoryTransport.createLinkedPair();
      const client = new Client({ name: "test", version: "0" });
      await Promise.all([server.connect(a), client.connect(b)]);
      const results = [];
      for (const [name, args] of CALLS) results.push(await client.callTool({ name, arguments: args }));
      const journal = session.doc!.journal.entries.map((e) => [e.seq, e.op, e.summary, e.after.length]);
      link?.close();
      await host?.close();
      await session.close();
      return { results: JSON.parse(JSON.stringify(results).replaceAll(workspace, "<workspace>")) as unknown, journal };
    };
    const plain = await run();
    expect(await run(2)).toEqual(plain);
    expect(await run(3)).toEqual(plain);
  });
});

