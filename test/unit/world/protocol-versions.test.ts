async function pair(hostOpts: Parameters<typeof FakeHost.start>[0] = {}, bridgeOpts: Partial<ConstructorParameters<typeof Bridge>[0]> = {}) {
  const host = await FakeHost.start(hostOpts);
  hosts.push(host);
  const bridge = new Bridge({ instanceDir: host.instanceDir, volatile: DEFAULT_VOLATILE, reconnect: false, ...bridgeOpts });
  bridges.push(bridge);
  const hello = await bridge.connect();
  return { host, bridge, hello };
}

